def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def read(p):
    p = Path(p)
    if not p.exists():
        return []
    with open(p, encoding="utf-8-sig", errors="replace", newline="") as fh:
        return list(csv.DictReader(fh))


def header_of(p):
    with open(p, encoding="utf-8-sig", errors="replace", newline="") as fh:
        return next(csv.reader(fh), [])


def profile(p, cols):
    rows = read(p)
    n = len(rows)
    return {c: {"n_rows": n,
                "pct_filled": round(
                    sum(1 for r in rows if (r.get(c) or "").strip())
                    * 100.0 / n, 1) if n else 0.0}
            for c in cols}


def write_frag(path, rows):
    if path.exists():
        b = path.with_suffix(path.suffix + f".bak_{TODAY}_pre263")
        if not b.exists():
            shutil.copy2(path, b)
    part = path.with_suffix(path.suffix + ".part")
    with open(part, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    part.replace(path)


def main():
    print("=== Cedar Press 263: register 262's repair columns ===\n")
    m87 = load(CODE / "87_build_dataset_notes.py", "m87")
    m41 = load(CODE / "41_build_codebooks.py", "m41")

    groups, frag_rows = defaultdict(set), {}
    for p in sorted(FRAG.glob("*.csv")):
        if ".bak" in p.name:
            continue
        rows = read(p)
        if not rows:
            continue
        ds = rows[0]["dataset"]
        frag_rows[ds] = (p, rows)
        groups[ds] = {(r.get("variable") or "").strip().lower() for r in rows}

    added = 0
    for fname in TOUCHED:
        p = CLEAN / fname
        if not p.exists():
            print(f"  {fname:44s} ABSENT")
            continue
        hdr = header_of(p)
        ds, score = m87.match_group(hdr, groups)
        new = [c for c in hdr
               if c in DESCRIPTIONS and c.lower() not in groups.get(ds, set())]
        if not ds or score < 0.60:
            print(f"  {fname:44s} !! best block {ds or '(none)'} scores "
                  f"{score:.2f} - BELOW the 0.60 gate. Registering the new "
                  f"columns is what RAISES that score, so this is done anyway "
                  f"into the best-matching block.")
            if not ds:
                continue
        if not new:
            print(f"  {fname:44s} -> {ds:34s} (all present)")
            continue
        fpath, rows = frag_rows[ds]
        prof = profile(p, new)
        for c in new:
            rows.append({
                "dataset": ds, "variable": c, "type": "text",
                "units": "date" if c.endswith("_date") else "code",
                "pct_filled": prof[c]["pct_filled"],
                "n_rows": prof[c]["n_rows"],
                "published": "1" if m41.is_published(c) else "0",
                "access_tier": m41.access_tier(c),
                "description": DESCRIPTIONS[c],
                "generated": TODAY,
            })
            groups[ds].add(c.lower())
            added += 1
        write_frag(fpath, rows)
        print(f"  {fname:44s} -> {ds:34s} score {score:.2f}  +{len(new)} vars")

    print(f"\n  +{added} variables registered")
    print("\ncodebook_master.csv NOT written here. "
          "Run: py -3 code/cedar_codebook.py build")
    return 0


if __name__ == "__main__":
    sys.exit(main())
