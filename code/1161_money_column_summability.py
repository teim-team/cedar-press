def money(raw):
    """Parse a delivered money cell. Returns None when it is not a number."""
    s = (raw or "").strip().replace(",", "").replace("$", "")
    if not s or s in ("-", "NA", "N/A", "None", "nan", "NaN"):
        return None
    neg = s.startswith("(") and s.endswith(")")
    if neg:
        s = s[1:-1]
    try:
        v = float(s)
    except ValueError:
        return None
    if math.isnan(v) or math.isinf(v):
        return None
    return -v if neg else v


