def measure_file(fname, specs):
    """One streaming pass over one delivered file for every column declared on it."""
    path = DIST / fname
    if not path.exists():
        return {c: {"status": "UNMEASURED",
                    "reason": f"{fname} is not in dist/customer"} for _, c, _, _ in specs}

    with path.open(encoding="utf-8-sig", errors="replace", newline="") as fh:
        rd = csv.reader(fh)
        header = next(rd)
        idx = {h: i for i, h in enumerate(header)}

        live, results = [], {}
        for _, col, gk, ok in specs:
            if col not in idx:
                results[col] = {"status": "UNMEASURED",
                                "reason": f"column absent from {fname}"}
                continue
            if gk is not None and gk not in idx:
                results[col] = {"status": "UNMEASURED",
                                "reason": f"declared group key {gk} absent from {fname}"}
                continue
            live.append((col, gk, ok))
        if not live:
            return results

        # Per column the groups hold the FULL list of (order, value) pairs, not a
        # running summary. A single forward pass cannot judge monotonicity,
        # because the delivered file is not sorted by (group, date) - an earlier
        # attempt that tried refused 100% of the groups as "out of order", which
        # is a clean-looking result about nothing. The lists are sorted per group
        # afterwards, so the answer does not depend on the file's row order.
        n_rows = 0
        agg = {}
        for col, gk, ok in live:
            agg[col] = {"n_val": 0, "sum": 0.0, "n_keyed": 0,
                        "groups": defaultdict(list)}

        for row in rd:
            n_rows += 1
            for col, gk, ok in live:
                try:
                    v = money(row[idx[col]])
                except IndexError:
                    continue
                if v is None:
                    continue
                a = agg[col]
                a["n_val"] += 1
                a["sum"] += v
                if gk is None:
                    continue
                key = (row[idx[gk]] or "").strip()
                if not key:
                    continue
                a["n_keyed"] += 1
                a["groups"][key].append(
                    ((row[idx[ok]] or "").strip() if ok else "", v))

    for col, gk, ok in live:
        a = agg[col]
        r = {"status": "MEASURED", "rows_in_file": n_rows,
             "rows_with_value": a["n_val"], "sum_all_rows": a["sum"],
             "group_key": gk, "order_key": ok}
        if a["n_val"] == 0:
            r["status"] = "UNMEASURED"
            r["reason"] = "no parseable numeric value in any row"
            results[col] = r
            continue
        if gk is None:
            r["verdict"] = "TRANSACTION_ADDITIVE"
            r["verdict_basis"] = ("no group key is declared: the delivered row IS "
                                  "the grain, so there is nothing for the figure "
                                  "to be restated onto")
            r["correct_total"] = a["sum"]
            r["factor_if_summed"] = 1.0
            results[col] = r
            continue

        cov = a["n_keyed"] / a["n_val"]
        r["group_key_coverage"] = round(cov, 4)
        if a["n_keyed"] == 0:
            r["status"] = "UNMEASURED"
            r["reason"] = (f"declared group key {gk} is blank on every one of the "
                           f"{a['n_val']:,} rows carrying a value")
            results[col] = r
            continue
        # A group key that does not resolve on every row does NOT make the column
        # unmeasurable - it makes the verdict a statement about the keyed subset.
        # Saying so, with the share, beats both a refusal and a silent extension
        # to rows the key never reached.
        subset = cov < KEY_COVERAGE_FLOOR
        if subset:
            r["measured_on"] = (
                f"the {a['n_keyed']:,} of {a['n_val']:,} rows "
                f"({100.0 * cov:.1f}%) on which {gk} resolves; the remaining "
                f"{a['n_val'] - a['n_keyed']:,} rows carry no award key and are "
                f"NOT covered by this verdict")

        groups = a["groups"]
        n_g = len(groups)
        keyed_sum = 0.0
        sum_max = sum_last = 0.0
        n_m = const = near_const = mono = 0
        dvr_num = step_num = ramp_num = 0.0
        n_step = 0
        for pairs in groups.values():
            vals = [v for _, v in pairs]
            keyed_sum += sum(vals)
            mx = max(vals)
            sum_max += mx
            pairs_sorted = sorted(pairs, key=lambda p: p[0])
            sum_last += pairs_sorted[-1][1]
            if len(vals) == 1:
                continue
            n_m += 1
            uniq = set(vals)
            if len(uniq) == 1:
                const += 1
                near_const += 1
            else:
                mn = min(vals)
                if mx and abs(mx - mn) / abs(mx) <= NEAR_CONSTANT_DRIFT:
                    near_const += 1
                svals = [v for _, v in pairs_sorted]
                if all(b >= a2 for a2, b in zip(svals, svals[1:])):
                    mono += 1
            dvr_num += len(uniq) / len(vals)
            # AUTOCORRELATION, the statistic that tells a running total from a
            # partition. A restated figure moves in small steps off a large
            # base; independent per-row amounts do not. The two are otherwise
            # numerically identical - both give group_max / group_sum ~ 1/n -
            # which is why a constancy test alone misses a ceiling that FALLS on
            # a de-obligation. `total_award_value` is exactly that column.
            svals = [v for _, v in pairs_sorted]
            steps = [abs(b - a2) / max(abs(a2), abs(b))
                     for a2, b in zip(svals, svals[1:]) if max(abs(a2), abs(b)) > 0]
            if steps:
                step_num += sum(steps) / len(steps)
                n_step += 1
            mean_abs = sum(abs(x) for x in vals) / len(vals)
            if mean_abs > 0:
                ramp_num += abs(mx) / mean_abs
        dvr = dvr_num / n_m if n_m else None
        mean_step = step_num / n_step if n_step else None
        mean_ramp = ramp_num / n_m if n_m else None

        r.update({"n_groups": n_g, "n_multirow_groups": n_m,
                  "n_multirow_constant": const,
                  "n_multirow_near_constant": near_const,
                  "n_multirow_monotone_nondecreasing_not_constant": mono,
                  "mean_distinct_value_ratio": round(dvr, 4) if dvr is not None else None,
                  "mean_relative_step": round(mean_step, 4) if mean_step is not None else None,
                  "mean_max_over_mean": round(mean_ramp, 4) if mean_ramp is not None else None,
                  "sum_over_keyed_rows": keyed_sum,
                  "sum_of_group_max": sum_max, "sum_of_group_last": sum_last})
        base = keyed_sum if subset else a["sum"]
        r["sum_judged"] = base

        if n_m == 0:
            r["verdict"] = "TRANSACTION_ADDITIVE"
            r["verdict_basis"] = (f"every one of the {n_g:,} `{gk}` groups holds exactly "
                                  f"one row, so the delivered row is the grain")
            r["correct_total"] = base
        elif near_const / n_m >= CONSTANT_THRESHOLD:
            r["verdict"] = "SNAPSHOT_RESTATED_PER_ROW"
            r["verdict_basis"] = (
                f"{const:,} of {n_m:,} multi-row `{gk}` groups "
                f"({100.0 * const / n_m:.1f}%) hold ONE value repeated on every row, "
                f"and {near_const:,} ({100.0 * near_const / n_m:.1f}%) vary by no more "
                f"than {100 * NEAR_CONSTANT_DRIFT:.0f}%: an award- or entity-level "
                f"figure restated per row, which summing multiplies by the group size")
            r["correct_total"] = sum_max
        elif mean_step is not None and mean_step <= AUTOCORRELATION_MAX and ok:
            r["verdict"] = "CUMULATIVE_RESTATED_PER_ROW"
            r["verdict_basis"] = (
                f"inside a `{gk}` group, successive values ordered by `{ok}` differ by "
                f"only {100.0 * mean_step:.1f}% on average (threshold "
                f"{100.0 * AUTOCORRELATION_MAX:.0f}%), and {const:,} of {n_m:,} groups "
                f"({100.0 * const / n_m:.1f}%) never move at all: the column is ONE "
                f"award-level figure restated on each transaction - a running total or "
                f"a ceiling - not a per-row amount. "
                + (f"{mono:,} groups ({100.0 * mono / n_m:.1f}%) only ever rise; the "
                   f"rest fall on de-obligations, which is why a monotonicity test "
                   f"alone does not find this column" if mono else
                   "no group is monotone non-decreasing"))
            r["correct_total"] = sum_last
        elif mean_step is not None and mean_step <= AUTOCORRELATION_MAX:
            r["verdict"] = "RESTATED_PER_ROW_WITH_DRIFT"
            r["verdict_basis"] = (
                f"inside a `{gk}` group, successive values differ by only "
                f"{100.0 * mean_step:.1f}% on average and {const:,} of {n_m:,} groups "
                f"({100.0 * const / n_m:.1f}%) never move at all, so the figure is "
                f"restated per row rather than partitioned across them; no order "
                f"column is declared for this group, so the group's MAXIMUM is used "
                f"rather than its last value")
            r["correct_total"] = sum_max
        else:
            r["verdict"] = "ADDITIVE_WITHIN_GROUP"
            r["verdict_basis"] = (
                f"successive values inside a `{gk}` group differ by "
                f"{100.0 * (mean_step or 1):.1f}% on average - far above the "
                f"{100.0 * AUTOCORRELATION_MAX:.0f}% at which a column is one figure "
                f"being restated - and only {const:,} of {n_m:,} groups are constant: "
                f"the rows partition the group rather than restate it, so SUM is the "
                f"answer")
            r["correct_total"] = base
        ct = r["correct_total"]
        r["factor_if_summed"] = round(base / ct, 4) if ct else None
        results[col] = r
    return results


def measure_all():
    by_file = defaultdict(list)
    for s in SPEC:
        by_file[s[0]].append(s)
    out = {}
    for fname in sorted(by_file):
        sys.stdout.write(f"  measuring {fname} ...\n")
        sys.stdout.flush()
        for col, res in measure_file(fname, by_file[fname]).items():
            res["dataset"] = fname
            res["column"] = col
            note = FILTER_NOTE.get((fname, col))
            if note:
                res["row_filter"] = note
            warn = NAME_WARNING.get((fname, col))
            if warn:
                res["name_warning"] = warn
            out[f"{fname}::{col}"] = res
    return out


