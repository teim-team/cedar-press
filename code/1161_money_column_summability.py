def render_block(measured):
    L = [BEGIN,
         "## Per-column summability, measured on the delivered files "
         f"(workstream COLUMN-SUMMABILITY, `code/1161_money_column_summability.py`, {TODAY})",
         "",
         "*Owner, 2026-09-02, on what only a full-data check can answer: "
         "\"transaction totals versus cumulative snapshots are additive\" - i.e. "
         "whether they can be summed at all. This block answers it per column. "
         "Every figure is re-measured from `dist/customer/` by "
         "`py -3 code/1161_money_column_summability.py apply`; the machine-readable "
         "form is `docs/MONEY_COLUMN_SUMMABILITY.json` and the sentence to print is "
         "`1161.summability_warning(dataset, column)`. Do not retype a number out of "
         "this table.*",
         "",
         "*This file is written WHOLESALE by `code/574_ws1_money_and_conservation.py`, "
         "which preserves only marked blocks; this section lives inside a marked block "
         "named COLUMN-SUMMABILITY-1161 and no other block was touched. The marker "
         "literals are deliberately NOT repeated in this sentence - an earlier draft "
         "quoted them, and the writer's own search for the END marker then found the "
         "quote instead and truncated the block on rewrite.*",
         "",
         "**The four shapes.** `TRANSACTION_ADDITIVE` - one row is one movement of "
         "money, SUM is the answer. `ADDITIVE_WITHIN_GROUP` - the rows partition "
         "their group, SUM is the answer. `SNAPSHOT_RESTATED_PER_ROW` - an award- or "
         "entity-level figure copied onto every row of its group; SUM multiplies it "
         "by the group size. `CUMULATIVE_RESTATED_PER_ROW` - an award-to-date running "
         "total, so it CHANGES per row and still may not be summed; the answer is the "
         "last value per group. The last two are the ones a column name never warns "
         "you about.",
         "",
         "| dataset | column | verdict | rows | SUM(all rows) | correct total | factor if summed |",
         "|---|---|---|---:|---:|---:|---:|"]
    for k in sorted(measured):
        m = measured[k]
        if m.get("status") != "MEASURED":
            L.append(f"| `{m['dataset']}` | `{m['column']}` | **UNMEASURED** | | | | "
                     f"{m.get('reason','')} |")
            continue
        flag = ("**NEVER SUM** (" + m["verdict"] + ")" if m["verdict"] in NEVER_SUM
                else m["verdict"])
        star = " *" if m.get("measured_on") else ""
        L.append(f"| `{m['dataset']}` | `{m['column']}` | {flag}{star} | "
                 f"{m['rows_with_value']:,} | "
                 f"${m.get('sum_judged', m['sum_all_rows']):,.2f} | "
                 f"${m['correct_total']:,.2f} | "
                 f"{m['factor_if_summed']:,.2f}x |")
    L += ["", "### Every never-sum column, in one sentence each", ""]
    for k in sorted(measured):
        m = measured[k]
        if m.get("status") == "MEASURED" and m["verdict"] in NEVER_SUM:
            L.append(f"* {summability_warning(m['dataset'], m['column'], measured)}")
    L += ["", "### Where a row filter applies before summing", ""]
    for k in sorted(measured):
        m = measured[k]
        if m.get("row_filter"):
            L.append(f"* `{m['dataset']}` `{m['column']}` - {m['row_filter']}.")
    warned = [measured[k] for k in sorted(measured) if measured[k].get("name_warning")]
    if warned:
        L += ["", "### Where the column NAME says the opposite of the measurement", ""]
        for m in warned:
            L.append(f"* `{m['dataset']}` `{m['column']}` - {m['name_warning']}.")
    blank = [measured[k] for k in sorted(measured)
             if measured[k].get("status") != "MEASURED"
             and "no parseable numeric value" in (measured[k].get("reason") or "")]
    if blank:
        L += ["", "### Declared money columns that are EMPTY in the delivered file", "",
              "Not a summability verdict - a delivery finding. These columns reach the "
              "customer file with a header and no value on any row.", ""]
        for m in blank:
            L.append(f"* `{m['dataset']}` `{m['column']}` - "
                     f"{m.get('rows_in_file', 0):,} rows, none parseable as a number.")
    starred = [measured[k] for k in sorted(measured) if measured[k].get("measured_on")]
    if starred:
        L += ["", "### `*` - a verdict measured on a SUBSET, and which subset", ""]
        for m in starred:
            L.append(f"* `{m['dataset']}` `{m['column']}` - measured on "
                     f"{m['measured_on']}.")
    L += ["",
          "**What is DECLARED and what is MEASURED.** Which columns hold money, "
          "which column is the group the figure belongs to, and which column orders "
          "that group are declared in `1161.SPEC` - a machine cannot guess them. "
          "Constancy, monotonicity, the verdict, the two totals and the factor are "
          "all measured. A declared group key that is blank on more than "
          f"{100 * (1 - KEY_COVERAGE_FLOOR):.0f}% of the rows carrying a value is "
          "REFUSED and reported UNMEASURED rather than producing a clean verdict "
          "about nothing.",
          END]
    return "\n".join(L)


def write_block(text):
    md = RULES_MD.read_text(encoding="utf-8")
    if BEGIN in md and END in md:
        # rindex, not index: if any prose inside the block ever quotes the end
        # marker, index() finds the quote and the rewrite truncates the block.
        a, b = md.index(BEGIN), md.rindex(END) + len(END)
        md = md[:a] + text + md[b:]
    else:
        md = md.rstrip("\n") + "\n\n" + text + "\n"
    RULES_MD.write_text(md, encoding="utf-8", newline="\n")


