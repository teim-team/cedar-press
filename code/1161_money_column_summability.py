def _load():
    if not JSON_OUT.exists():
        return {}
    return json.loads(JSON_OUT.read_text(encoding="utf-8")).get("columns", {})


def summability_warning(dataset, column, measured=None):
    """One sentence, with its denominator stated. Never retype this."""
    m = (measured or _load()).get(f"{dataset}::{column}")
    if not m:
        return (f"`{column}` in `{dataset}` has NOT been measured for "
                f"summability. Do not total it until "
                f"`py -3 code/1161_money_column_summability.py apply` has run.")
    if m.get("status") != "MEASURED":
        return (f"`{column}` in `{dataset}`: UNMEASURED - {m.get('reason','no reason recorded')}. "
                f"Do not total it.")
    v = m["verdict"]
    scope = (" " + m["measured_on"]) if m.get("measured_on") else ""
    if v == "TRANSACTION_ADDITIVE":
        return (f"`{column}` in `{dataset}` is TRANSACTION-ADDITIVE: sum it over rows "
                f"{m.get('row_filter', '(no row filter recorded)')}. "
                f"{m['rows_with_value']:,} rows total ${m['sum_all_rows']:,.2f}. "
                f"{m['verdict_basis']}.")
    if v == "ADDITIVE_WITHIN_GROUP":
        return (f"`{column}` in `{dataset}` partitions its group "
                f"(`{m['group_key']}`) rather than restating it, so SUM is the "
                f"answer: {m['rows_with_value']:,} rows total ${m['sum_all_rows']:,.2f}. "
                f"{m['verdict_basis']}"
                + (f". Measured on{scope}" if scope else "") + ".")
    correct = m["correct_total"]
    fac = m["factor_if_summed"]
    how = {"CUMULATIVE_RESTATED_PER_ROW": "the LAST value per ",
           }.get(v, "one value per ")
    return (f"`{column}` in `{dataset}` MUST NOT BE SUMMED: {m['verdict_basis']}. "
            f"Summing gives ${m['sum_judged']:,.2f}, which is "
            f"{fac:,.2f}x the correct ${correct:,.2f} taken as {how}"
            f"`{m['group_key']}` over {m['n_groups']:,} groups"
            + (f", measured on{scope}" if scope else "") +
            ". Measured from the delivered file, not quoted.")


