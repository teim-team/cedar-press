def cmd_verify():
    fails = []
    if not JSON_OUT.exists():
        out("V1 FAIL: docs/MONEY_COLUMN_SUMMABILITY.json is absent")
        return 1
    doc = json.loads(JSON_OUT.read_text(encoding="utf-8"))
    cols = doc.get("columns", {})

    present = 0
    for fname, col, _, _ in SPEC:
        if not (DIST / fname).exists():
            continue
        with (DIST / fname).open(encoding="utf-8-sig", errors="replace", newline="") as fh:
            header = next(csv.reader(fh))
        if col not in header:
            continue
        present += 1
        if f"{fname}::{col}" not in cols:
            fails.append(f"V1: {fname}::{col} is in the delivered file and not in the JSON")
    out(f"V1 declared columns present in dist/customer: {present}; covered by the JSON: "
        f"{present - sum(1 for f in fails if f.startswith('V1'))}")

    never = [m for m in cols.values()
             if m.get("status") == "MEASURED" and m.get("verdict") in NEVER_SUM]
    out(f"V2 never-sum columns recorded: {len(never)} (floor {MIN_NEVER_SUM})")
    if len(never) < MIN_NEVER_SUM:
        fails.append(f"V2: only {len(never)} never-sum columns; the known-bad set is "
                     f"at least {MIN_NEVER_SUM}. The measurement found the wrong thing.")

    tav = cols.get("contractors.csv::total_award_value", {})
    ok3 = (tav.get("status") == "MEASURED" and tav.get("verdict") in NEVER_SUM
           and (tav.get("factor_if_summed") or 0) > 2.0)
    out(f"V3 contractors.total_award_value: verdict={tav.get('verdict')} "
        f"factor={tav.get('factor_if_summed')}")
    if not ok3:
        fails.append("V3: contractors.total_award_value is not recorded as a never-sum "
                     "column with a factor above 2.0 - this is the instance the "
                     "customer review named")

    md = RULES_MD.read_text(encoding="utf-8") if RULES_MD.exists() else ""
    if BEGIN not in md or END not in md:
        fails.append(f"V4: the marked block {BEGIN} is absent from "
                     f"{RULES_MD.relative_to(CEDAR)}")
    elif tav.get("factor_if_summed"):
        want = f"{tav['factor_if_summed']:,.2f}x"
        block = md[md.index(BEGIN):md.rindex(END)]
        if want not in block:
            fails.append(f"V4: the block does not state {want} for "
                         f"contractors.total_award_value; the document and the JSON "
                         f"disagree")
    out(f"V4 marked block present and agreeing with the JSON: "
        f"{'no' if any(f.startswith('V4') for f in fails) else 'yes'}")

    out("")
    if fails:
        for f in fails:
            out("FAIL  " + f)
        return 1
    out("PASS  all four invariants")
    return 0


def cmd_fixtures():
    """Prove each invariant FIRES. Inject, assert exit 1 AND the named line,
    restore, assert exit 0. A check that has never failed on purpose is not
    known to work."""
    import contextlib
    import io

    if not JSON_OUT.exists():
        out("fixtures: run `apply` first - there is nothing to corrupt")
        return 1
    original = JSON_OUT.read_text(encoding="utf-8")
    original_md = RULES_MD.read_text(encoding="utf-8")
    doc = json.loads(original)

    def run():
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = cmd_verify()
        return rc, buf.getvalue()

    results = []
    try:
        rc, txt = run()
        results.append(("baseline PASS", rc == 0, f"exit {rc}"))

        # V1 + V3: drop the named column entirely
        d = json.loads(original)
        d["columns"].pop("contractors.csv::total_award_value", None)
        JSON_OUT.write_text(json.dumps(d), encoding="utf-8")
        rc, txt = run()
        results.append(("V1 fires when a delivered column is missing from the JSON",
                        rc == 1 and "V1:" in txt, f"exit {rc}"))
        results.append(("V3 fires when total_award_value is absent",
                        rc == 1 and "V3:" in txt, f"exit {rc}"))

        # V2: strip every never-sum verdict
        d = json.loads(original)
        for m in d["columns"].values():
            if m.get("verdict") in NEVER_SUM:
                m["verdict"] = "TRANSACTION_ADDITIVE"
        JSON_OUT.write_text(json.dumps(d), encoding="utf-8")
        rc, txt = run()
        results.append(("V2 fires when no never-sum column is recorded",
                        rc == 1 and "V2:" in txt, f"exit {rc}"))

        # V4: move the factor in the JSON so the document disagrees
        d = json.loads(original)
        d["columns"]["contractors.csv::total_award_value"]["factor_if_summed"] = 99.99
        JSON_OUT.write_text(json.dumps(d), encoding="utf-8")
        rc, txt = run()
        results.append(("V4 fires when the document and the JSON disagree",
                        rc == 1 and "V4:" in txt, f"exit {rc}"))

        # V4 again: remove the block from the document
        JSON_OUT.write_text(original, encoding="utf-8")
        a = original_md.index(BEGIN)
        b = original_md.rindex(END) + len(END)
        RULES_MD.write_text(original_md[:a] + original_md[b:], encoding="utf-8",
                            newline="\n")
        rc, txt = run()
        results.append(("V4 fires when the marked block is absent",
                        rc == 1 and "V4:" in txt, f"exit {rc}"))
    finally:
        JSON_OUT.write_text(original, encoding="utf-8")
        RULES_MD.write_text(original_md, encoding="utf-8", newline="\n")

    rc, _ = run()
    results.append(("restored, PASS again", rc == 0, f"exit {rc}"))

    out("1161 fixtures - each invariant must FIRE on an injected violation")
    out("=" * 78)
    bad = 0
    for name, ok, detail in results:
        out(f"  [{'ok ' if ok else 'FAIL'}] {name}  ({detail})")
        bad += 0 if ok else 1
    out("")
    out("all fixtures fired" if not bad else f"{bad} fixture(s) did not fire")
    return 0 if not bad else 1


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "report"
    if cmd == "report":
        cmd_report(False)
        return 0
    if cmd == "fixtures":
        return cmd_fixtures()
    if cmd == "apply":
        cmd_report(True)
        return 0
    if cmd == "verify":
        return cmd_verify()
    out(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
