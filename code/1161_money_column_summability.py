# Fraction of multi-row groups that must agree before a shape is declared.
CONSTANT_THRESHOLD = 0.95
# Within-group spread, (max-min)/max, under which a group counts as restated
# rather than partitioned. FSRS primes restate a revised prime award amount in a
# later report; that is a correction to one figure, not a second figure.
NEAR_CONSTANT_DRIFT = 0.02
# `mean_distinct_value_ratio` (distinct values / rows, per multi-row group) is
# REPORTED and is not decisive: it does not separate a running total, which
# carries a distinct value on most rows, from a partition, which does the same.
#
# THE DECISIVE STATISTIC. Mean, over multi-row groups, of the average relative
# step |v(i) - v(i-1)| / max(|v(i)|, |v(i-1)|) between successive values ordered
# by the group's own date column. A figure being RESTATED moves in small steps
# off a large base; independent per-row amounts do not. Measured 2026-09-02 on
# the delivered files, the two populations do not overlap and are not close:
#
#   RESTATED   subcontracting.prime_award_amount            0.010
#              funding.total_face_value_of_loan             0.000
#              contractors.total_award_value                0.304
#              contractors.total_award_value_real2025       0.319
#   ADDITIVE   funding.obligated_usd_real2025               0.761
#              funding.obligated_usd                        0.767
#              contractors.total_obligations_real2025       0.967
#              contractors.total_obligations                0.970
#
# The threshold sits in the empty band between 0.319 and 0.761. Re-read those
# figures out of the report before moving it; a threshold tuned to one build is
# the failure this repo has twenty-four instances of.
AUTOCORRELATION_MAX = 0.50
# Below this share of rows carrying a value, the group key does not resolve on
# the whole column and the verdict is reported as covering the keyed SUBSET.
KEY_COVERAGE_FLOOR = 0.90

MIN_NEVER_SUM = 8

NEVER_SUM = ("SNAPSHOT_RESTATED_PER_ROW", "CUMULATIVE_RESTATED_PER_ROW",
             "RESTATED_PER_ROW_WITH_DRIFT")


