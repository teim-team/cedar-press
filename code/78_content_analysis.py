def fr_tier(r):
    """Evidence tier for 'is this document ABOUT Indian Country?'

    title_subject     - a Native term is in the TITLE. Strongest available
                        evidence short of reading the body.
    abstract_subject  - Native term in the abstract but not the title.
    weak_term_only    - only an ambiguous term ('reservation', 'Pueblo',
                        which also mean campsite bookings and New Mexico towns).
    body_only         - no Native term in any field we hold. UNVERIFIABLE from
                        this dataset. Not a claim that it is irrelevant - a
                        statement that we cannot see.
    """
    t, a = r.get("title") or "", r.get("abstract") or ""
    if FR_STRONG.search(t):
        return "title_subject"
    if FR_STRONG.search(a):
        return "abstract_subject"
    if FR_WEAK.search(t) or FR_WEAK.search(a):
        return "weak_term_only"
    return "body_only_unverifiable"


def fr_themes(r):
    txt = (r.get("title") or "") + " || " + (r.get("abstract") or "")
    return [n for n, rx in FR_RX if rx.search(txt)]


def build_fr(rows):
    print("\n[2] Federal Register: what the government does, by type")
    tiers = Counter()
    out, theme_year, tier_year = [], defaultdict(Counter), defaultdict(Counter)
    classifiable_year = Counter()
    agency_year = defaultdict(Counter)
    agency_theme = defaultdict(Counter)

    for r in rows:
        t = fr_tier(r)
        tiers[t] += 1
        yr = (r.get("publication_date") or "")[:4]
        yr = int(yr) if yr.isdigit() else None
        if yr:
            tier_year[t][yr] += 1
        classifiable = t in ("title_subject", "abstract_subject")
        th = fr_themes(r) if classifiable else []
        if classifiable and yr:
            classifiable_year[yr] += 1
            for x in th:
                theme_year[x][yr] += 1
        if classifiable:
            for a in (r.get("agency_names") or "").split("|"):
                a = a.strip()
                if a:
                    if yr:
                        agency_year[a][yr] += 1
                    for x in th:
                        agency_theme[a][x] += 1
        out.append({
            "document_number": r.get("document_number", ""),
            "publication_date": r.get("publication_date", ""),
            "publication_year": yr or "",
            "type": r.get("type", ""),
            "title": r.get("title", ""),
            "agency_names": r.get("agency_names", ""),
            "relevance_tier": t,
            "content_classifiable": int(classifiable),
            "themes": "|".join(th),
            "n_themes": len(th),
            "classifier": "78_content_analysis.py::fr_themes",
            "classifier_version": TODAY,
            "html_url": r.get("html_url", ""),
        })

    write_csv(CLEAN / "fr_content_classification.csv", out)

    ser = []
    yrs = sorted({r["publication_year"] for r in out if r["publication_year"]})
    for th in sorted(theme_year):
        for y in yrs:
            n = theme_year[th][y]
            ser.append({
                "theme": th, "publication_year": y, "n_documents": n,
                "n_classifiable_documents_that_year": classifiable_year[y],
                "share_of_classifiable":
                    round(n / classifiable_year[y], 4) if classifiable_year[y] else "",
            })
    write_csv(CLEAN / "fr_theme_year.csv", ser)

    tser = [{"relevance_tier": t, "publication_year": y, "n_documents": tier_year[t][y]}
            for t in sorted(tier_year) for y in yrs if tier_year[t][y]]
    write_csv(CLEAN / "fr_relevance_tier_year.csv", tser)

    print("  relevance tiers: " + ", ".join(
        f"{k}={v:,} ({100*v/len(rows):.1f}%)" for k, v in tiers.most_common()))
    return out, tiers, theme_year, classifiable_year, agency_year, agency_theme


