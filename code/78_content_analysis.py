# Segments that say nothing: "general tribal issues", "monitor Indian
# legislation". These are not an unclassified failure, they are a filer
# declining to disclose, and they are counted and published as such.
LOBBY_GENERIC = re.compile(
    r"^(general |monitor|monitoring|various |all )?"
    r"(matters?|issues?|legislation|activit\w+|representation|advocacy)?[ ,]*"
    r"(relat\w+ to |regarding |concerning |affecting |pertaining to |on )?"
    r"(general |various |all )?"
    r"(native american|american indian|indian|tribal|tribe|alaska native)[ a-z]*"
    r"(issues?|matters?|affairs|legislation|policy|interests?|programs?|"
    r"representation|concerns?|relations|government|country|nations?)?[ .]*$",
    re.I)


def lobby_segments(txt):
    """Split a specific_issues_text blob into deduplicated issue lines."""
    txt = html.unescape(html.unescape(txt or ""))
    out = set()
    for blob in txt.split("|||"):
        for line in re.split(r"[\n\r;]+", blob):
            line = re.sub(r"\s+", " ", line).strip(" .,-\u2022*\t")
            if len(line) >= 4:
                out.add(line)
    return sorted(out)


def lobby_classify(seg):
    fams = {n for n, rx in LOBBY_RX if rx.search(seg)}
    if fams:
        return fams, "matched"
    if LOBBY_GENERIC.match(seg):
        return set(), "generic_boilerplate"
    return set(), "unclassified"


def build_lobbying(rows):
    print("\n[1] Lobbying: what Indian Country lobbies about")
    per_filing, seg_status = [], Counter()
    fam_year = defaultdict(Counter)          # family -> year -> filings
    year_total = Counter()
    coded_year = Counter()

    for r in rows:
        yr = (r.get("filing_year") or "").strip()
        if not yr.isdigit():
            continue
        yr = int(yr)
        year_total[yr] += 1
        segs = lobby_segments(r.get("specific_issues_text"))
        fams, statuses = set(), Counter()
        for s in segs:
            f, st = lobby_classify(s)
            fams |= f
            statuses[st] += 1
            seg_status[st] += 1
        if not segs:
            seg_status["no_text_disclosed"] += 1
        per_filing.append({
            "filing_uuid": r.get("filing_uuid", ""),
            "filing_year": yr,
            "client_name": r.get("client_name", ""),
            "entity_id": r.get("entity_id", ""),
            "lda_issue_codes": r.get("lobbying_issues_codes", ""),
            "n_segments": len(segs),
            "n_segments_matched": statuses.get("matched", 0),
            "n_segments_generic": statuses.get("generic_boilerplate", 0),
            "n_segments_unclassified": statuses.get("unclassified", 0),
            "issue_families": "|".join(sorted(fams)),
            "n_issue_families": len(fams),
            "text_status": ("no_text" if not segs else
                            "classified" if fams else
                            "generic_only" if statuses.get("generic_boilerplate")
                            else "unclassified_only"),
            "classifier": "78_content_analysis.py::lobby_classify",
            "classifier_version": TODAY,
        })
        if fams:
            coded_year[yr] += 1
            for f in fams:
                fam_year[f][yr] += 1

    write_csv(CLEAN / "lobbying_issue_families_filing.csv", per_filing)

    # Two denominators, and the difference matters more than it looks.
    #
    # share_of_classified_filings is contaminated: the mean number of issue
    # families disclosed per filing rose from ~2.0 in 2002-03 to ~3.1 by the
    # 2020s. Against that denominator almost every family "rises", which is a
    # fact about filing verbosity, not about what tribes lobby on. Read alone it
    # would have produced a whole page of spurious growth findings.
    #
    # share_of_family_mentions is compositional - each family's share of all
    # family mentions that year - and is neutral to how much a filer wrote.
    # It is the series to quote for change over time.
    mentions_year = Counter()
    for f in fam_year:
        for y, n in fam_year[f].items():
            mentions_year[y] += n

    series = []
    years = sorted(year_total)
    for f in sorted(fam_year):
        for y in years:
            n = fam_year[f][y]
            series.append({
                "issue_family": f, "filing_year": y, "n_filings": n,
                "n_filings_with_any_family": coded_year[y],
                "share_of_classified_filings":
                    round(n / coded_year[y], 4) if coded_year[y] else "",
                "n_family_mentions_that_year": mentions_year[y],
                "share_of_family_mentions":
                    round(n / mentions_year[y], 4) if mentions_year[y] else "",
                "n_filings_total_that_year": year_total[y],
                "preferred_series_for_trend": "share_of_family_mentions",
            })
    write_csv(CLEAN / "lobbying_issue_family_year.csv", series)

    verb = []
    for y in years:
        fl = [r for r in per_filing
              if r["filing_year"] == y and r["text_status"] == "classified"]
        if fl:
            verb.append({
                "filing_year": y, "n_classified_filings": len(fl),
                "mean_issue_families_per_filing":
                    round(sum(r["n_issue_families"] for r in fl) / len(fl), 3),
                "mean_segments_per_filing":
                    round(sum(r["n_segments"] for r in fl) / len(fl), 3),
            })
    write_csv(CLEAN / "lobbying_disclosure_verbosity_year.csv", verb)

    print(f"  segment outcomes: {dict(seg_status)}")
    return per_filing, seg_status, year_total, coded_year, fam_year


