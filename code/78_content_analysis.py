def build_agencies(fr_rows, lob_rows, agency_year):
    print("\n[3] Agencies: policy attention vs advocacy targeting")

    # FR side - only documents we can verify are tribal-subject.
    fr_dept, fr_dept_year = Counter(), defaultdict(Counter)
    for r in fr_rows:
        if not r["content_classifiable"]:
            continue
        y = r["publication_year"]
        for a in (r["agency_names"] or "").split("|"):
            a = a.strip()
            if not a:
                continue
            d = norm_agency(a)
            fr_dept[d] += 1
            if y:
                fr_dept_year[d][y] += 1

    # Lobbying side - government_entities is filer-reported, not inferred.
    lob_dept, lob_dept_year = Counter(), defaultdict(Counter)
    raw_targets = Counter()
    for r in lob_rows:
        y = (r.get("filing_year") or "").strip()
        y = int(y) if y.isdigit() else None
        seen = set()
        for a in (r.get("government_entities") or "").split("|"):
            a = a.strip()
            if not a:
                continue
            raw_targets[a] += 1
            d = norm_agency(a)
            if d in seen:
                continue
            seen.add(d)
            lob_dept[d] += 1
            if y:
                lob_dept_year[d][y] += 1

    fr_tot = sum(fr_dept.values()) or 1
    lob_tot = sum(lob_dept.values()) or 1
    # Congress publishes nothing in the Federal Register, so a "Congress" gap of
    # +42pp measures the two sources' definitions, not anybody's behaviour. The
    # executive-only shares are the ones that compare like with like.
    EXCL = {"Congress"}
    fr_x = sum(v for k, v in fr_dept.items() if k not in EXCL) or 1
    lob_x = sum(v for k, v in lob_dept.items() if k not in EXCL) or 1
    gap = []
    for d in sorted(set(fr_dept) | set(lob_dept)):
        fs, ls = fr_dept[d] / fr_tot, lob_dept[d] / lob_tot
        gap.append({
            "department": d,
            "fr_documents": fr_dept[d],
            "fr_share_of_agency_mentions": round(fs, 4),
            "lobbying_filings_targeting": lob_dept[d],
            "lobbying_share_of_targets": round(ls, 4),
            "advocacy_minus_attention_pp": round((ls - fs) * 100, 2),
            "fr_share_executive_only":
                "" if d in EXCL else round(fr_dept[d] / fr_x, 4),
            "lobbying_share_executive_only":
                "" if d in EXCL else round(lob_dept[d] / lob_x, 4),
            "gap_pp_executive_only": "" if d in EXCL else round(
                (lob_dept[d] / lob_x - fr_dept[d] / fr_x) * 100, 2),
            "fr_basis": "agency_names on classifiable (title/abstract-subject) FR documents",
            "lobbying_basis": "government_entities as reported by the filer",
        })
    gap.sort(key=lambda r: -abs(r["gap_pp_executive_only"]
                               if r["gap_pp_executive_only"] != "" else 0))
    write_csv(CLEAN / "agency_attention_vs_advocacy.csv", gap)

    ser = []
    yrs = sorted({y for d in fr_dept_year for y in fr_dept_year[d]} |
                 {y for d in lob_dept_year for y in lob_dept_year[d]})
    for d in sorted(set(fr_dept) | set(lob_dept)):
        for y in yrs:
            f, l = fr_dept_year[d].get(y, 0), lob_dept_year[d].get(y, 0)
            if f or l:
                ser.append({"department": d, "year": y,
                            "fr_documents": f, "lobbying_filings_targeting": l})
    write_csv(CLEAN / "agency_attention_vs_advocacy_year.csv", ser)

    write_csv(CLEAN / "lobbying_target_entities.csv",
              [{"government_entity_as_filed": k, "n_filings": v,
                "normalized_department": norm_agency(k)}
               for k, v in raw_targets.most_common()])
    return gap, fr_dept, lob_dept


