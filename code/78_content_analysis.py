def read_csv(p):
    p = Path(p)
    if not p.exists():
        return []
    with open(p, encoding="utf-8-sig", errors="replace", newline="") as fh:
        return list(csv.DictReader(fh))


def write_csv(p, rows, cols=None):
    p = Path(p)
    if not rows:
        print(f"  (skipped {p.name}: no rows)")
        return
    # Union the keys across ALL rows, first-seen order - not just rows[0].
    #
    # Taking columns from the first row silently dropped
    # `estimated_true_tribal_subject_documents` from content_analysis_accuracy.csv,
    # because the first row was a classifier that has no such field and
    # extrasaction="ignore" then discarded it everywhere. The doc cited a number
    # the CSV did not contain, which is exactly the failure standing rule 10
    # exists to prevent.
    if cols is None:
        cols, seen = [], set()
        for r in rows:
            for k in r:
                if k not in seen:
                    seen.add(k)
                    cols.append(k)
    with open(p, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    print(f"  wrote {p.name:52s} {len(rows):>7,} rows")


