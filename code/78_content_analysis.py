def _setify(s):
    return {x.strip() for x in (s or "").split("|") if x.strip()}


def score_multilabel(rows, rule_col, hand_col):
    """Per-item exact match plus micro precision/recall over labels."""
    done = [r for r in rows if (r.get(hand_col) or "").strip()]
    if not done:
        return None
    tp = fp = fn = exact = 0
    confusion = []
    for r in done:
        R, H = _setify(r[rule_col]), _setify(r[hand_col])
        if H == {"NONE"}:
            H = set()
        if R == H:
            exact += 1
        else:
            confusion.append(r)
        tp += len(R & H)
        fp += len(R - H)
        fn += len(H - R)
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    return {
        "n_hand_coded": len(done),
        "exact_set_match": exact,
        "exact_set_match_rate": round(exact / len(done), 4),
        "label_precision": round(prec, 4),
        "label_recall": round(rec, 4),
        "label_f1": round(2 * prec * rec / (prec + rec), 4) if prec + rec else 0.0,
        "labels_true_positive": tp,
        "labels_false_positive": fp,
        "labels_false_negative": fn,
        "_confusion": confusion,
    }


def score_binary(rows, rule_col, hand_col, positive_tiers):
    done = [r for r in rows if (r.get(hand_col) or "").strip()]
    if not done:
        return None
    tp = tn = fp = fn = 0
    confusion = []
    for r in done:
        pred = r[rule_col] in positive_tiers
        truth = r[hand_col].strip().lower() in ("y", "yes", "1", "true")
        if pred and truth:
            tp += 1
        elif not pred and not truth:
            tn += 1
        elif pred and not truth:
            fp += 1
            confusion.append(r)
        else:
            fn += 1
            confusion.append(r)
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    return {
        "n_hand_coded": len(done),
        "accuracy": round((tp + tn) / len(done), 4),
        "precision": round(prec, 4), "recall": round(rec, 4),
        "f1": round(2 * prec * rec / (prec + rec), 4) if prec + rec else 0.0,
        "tp": tp, "tn": tn, "false_positive": fp, "false_negative": fn,
        "_confusion": confusion,
    }


def score_stratified(rows, tier_counts, positive_tiers):
    """Reweight a stratified audit back to the corpus.

    The relevance sample deliberately oversamples the small tiers (40 of 9,523
    title_subject, but 25 of 132,964 body_only). Its raw accuracy is therefore a
    number about the SAMPLE, not about the corpus, and publishing it as a
    corpus error rate would overstate how wrong we are by a wide margin.
    Reweighting each stratum by its true size fixes that.
    """
    done = [r for r in rows if (r.get("hand_is_tribal_subject") or "").strip()]
    if not done:
        return None
    by = defaultdict(list)
    for r in done:
        by[r["rule_tier"]].append(r)
    tp = fp = fn = tn = 0.0
    per = []
    for tier, rs in by.items():
        N = tier_counts.get(tier, 0)
        if not rs or not N:
            continue
        w = N / len(rs)
        pred = tier in positive_tiers
        pos = sum(1 for r in rs
                  if r["hand_is_tribal_subject"].strip().lower() in ("y", "yes", "1"))
        neg = len(rs) - pos
        if pred:
            tp += pos * w
            fp += neg * w
        else:
            fn += pos * w
            tn += neg * w
        per.append({"tier": tier, "corpus_documents": N, "sampled": len(rs),
                    "hand_coded_tribal_subject": pos,
                    "stratum_positive_rate": round(pos / len(rs), 4)})
    tot = tp + fp + fn + tn
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    return {
        "weighted_accuracy": round((tp + tn) / tot, 4) if tot else 0.0,
        "weighted_precision": round(prec, 4),
        "weighted_recall": round(rec, 4),
        "estimated_true_tribal_subject_documents": int(round(tp + fn)),
        "estimated_share_of_corpus": round((tp + fn) / tot, 4) if tot else 0.0,
        "flagged_classifiable": int(round(tp + fp)),
        "per_stratum": per,
    }


