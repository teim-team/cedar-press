# A first pass counted 2,795 "consultation notices" and was wrong. Every NAGPRA
# inventory notice contains the sentence "in consultation with the appropriate
# Indian Tribes or Native Hawaiian organizations" - which is evidence that
# consultation HAPPENED, but is not a notice announcing a consultation. Counting
# them together inflates the consultation record several-fold and would have
# been published as a finding.
#
# So two distinct measures, never summed:
#   notice   - the document's purpose is to convene or announce consultation
#   referenced - the document reports consultation already undertaken
CONSULT_TITLE = re.compile(r"\bconsultation\b|\bconsult(ing|s)?\b", re.I)
CONSULT_SUBJECT_ABS = re.compile(
    r"tribal consultation|consultation session|consultation meeting|"
    r"consultation (period|process|policy|framework|hearing)|"
    r"government-to-government consultation|"
    r"(will|to) (conduct|hold|convene|initiate)\w* .{0,40}consultation|"
    r"consult(ing|ation)? with (federally recognized |affected |interested )?"
    r"(indian )?trib(e|es|al)", re.I)
# The boilerplate that must not count as a consultation notice.
CONSULT_BOILERPLATE = re.compile(
    r"in consultation with the appropriate indian trib|"
    r"in consultation with the appropriate trib", re.I)


def build_consultation(fr_rows_raw, fr_out):
    print("\n[4] The consultation record")
    idx = {r["document_number"]: r for r in fr_out}
    rows, referenced = [], []
    for r in fr_rows_raw:
        o = idx.get(r.get("document_number", ""))
        if not o or not o["content_classifiable"]:
            continue
        t, a = r.get("title") or "", r.get("abstract") or ""
        boiler = bool(CONSULT_BOILERPLATE.search(a))
        in_title = bool(CONSULT_TITLE.search(t))
        in_abs = bool(CONSULT_SUBJECT_ABS.search(a)) and not boiler
        if boiler and not in_title:
            referenced.append({
                "document_number": r.get("document_number", ""),
                "publication_year": (r.get("publication_date") or "")[:4],
                "title": t,
                "agency_names": r.get("agency_names", ""),
                "basis": "abstract reports consultation already undertaken "
                         "(NAGPRA-style boilerplate); NOT a consultation notice",
            })
        if not (in_title or in_abs):
            continue
        rows.append({
            "document_number": r.get("document_number", ""),
            "publication_date": r.get("publication_date", ""),
            "publication_year": (r.get("publication_date") or "")[:4],
            "type": r.get("type", ""),
            "title": t,
            "agency_names": r.get("agency_names", ""),
            "normalized_departments": "|".join(sorted(
                {norm_agency(x.strip())
                 for x in (r.get("agency_names") or "").split("|") if x.strip()})),
            "consultation_signal": "title" if in_title else "abstract",
            "comment_url": r.get("comment_url", ""),
            "html_url": r.get("html_url", ""),
            "relevance_tier": o["relevance_tier"],
        })
    write_csv(CLEAN / "fr_consultation_notices.csv", rows)
    write_csv(CLEAN / "fr_consultation_referenced.csv", referenced)

    yc = Counter(r["publication_year"] for r in rows)
    rc = Counter(r["publication_year"] for r in referenced)
    dc = Counter(d for r in rows for d in r["normalized_departments"].split("|"))
    ser = [{"publication_year": y,
            "n_consultation_notices": yc.get(y, 0),
            "n_documents_reporting_consultation_undertaken": rc.get(y, 0)}
           for y in sorted(set(yc) | set(rc))]
    write_csv(CLEAN / "fr_consultation_year.csv", ser)

    write_csv(CLEAN / "fr_consultation_by_agency.csv",
              [{"normalized_department": k, "n_consultation_notices": v,
                "share_of_notices": round(v / len(rows), 4) if rows else ""}
               for k, v in dc.most_common()])
    print(f"  {len(rows):,} consultation NOTICES "
          f"(title-signal {sum(1 for r in rows if r['consultation_signal']=='title'):,}); "
          f"{len(referenced):,} documents merely REPORTING consultation")
    return rows, yc, dc


