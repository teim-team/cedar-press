    print("\n[6] Corpus diagnostics and the corrected NAGPRA series")
    idx = {r["document_number"]: r for r in fr_out}

    nag, per_year = [], defaultdict(lambda: [0, 0])
    for r in fr_rows_raw:
        t = r.get("title") or ""
        if not NAGPRA_TITLE.search(t):
            continue
        y = (r.get("publication_date") or "")[:4]
        has_abs = bool((r.get("abstract") or "").strip())
        o = idx.get(r.get("document_number", ""))
        per_year[y][0] += 1
        if has_abs:
            per_year[y][1] += 1
        nag.append({
            "document_number": r.get("document_number", ""),
            "publication_date": r.get("publication_date", ""),
            "publication_year": y,
            "title": t,
            "agency_names": r.get("agency_names", ""),
            "notice_kind": ("inventory_completion"
                            if re.search(r"inventory completion", t, re.I)
                            else "intent_to_repatriate"),
            "has_abstract": int(has_abs),
            "relevance_tier_from_tier_rule":
                o["relevance_tier"] if o else "",
            "missed_by_tier_rule":
                int(bool(o) and not o["content_classifiable"]),
            "basis": "FR standardised notice title prescribed by 43 CFR 10; "
                     "does not depend on abstract availability",
        })
    write_csv(CLEAN / "fr_nagpra_title_index.csv", nag)
    write_csv(CLEAN / "fr_nagpra_title_index_year.csv",
              [{"publication_year": y,
                "n_nagpra_notices": per_year[y][0],
                "n_with_abstract": per_year[y][1],
                "share_with_abstract": round(per_year[y][1] / per_year[y][0], 4)
                if per_year[y][0] else ""}
               for y in sorted(per_year) if y])
    missed = sum(r["missed_by_tier_rule"] for r in nag)
    print(f"  {len(nag):,} NAGPRA notices by title; {missed:,} "
          f"({100*missed/len(nag):.1f}%) were missed by the relevance tier rule")

    # Abstract availability is the single biggest determinant of what we can
    # classify at all, so it is published as a series in its own right.
    ab = defaultdict(lambda: [0, 0])
    for r in fr_rows_raw:
        y = (r.get("publication_date") or "")[:4]
        if not y:
            continue
        ab[y][0] += 1
        if (r.get("abstract") or "").strip():
            ab[y][1] += 1
    write_csv(CLEAN / "fr_abstract_availability_year.csv",
              [{"publication_year": y, "n_documents": ab[y][0],
                "n_with_abstract": ab[y][1],
                "share_with_abstract": round(ab[y][1] / ab[y][0], 4)}
               for y in sorted(ab)])
    return nag, missed


