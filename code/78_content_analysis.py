r"""
Cedar Press - 78: Content analysis of the four text corpora.

WHY THIS EXISTS
---------------
Elijah, 2026-08-06: "we also should probably do content analysis on some of
these too"

Cedar Press holds four large text corpora that are currently used only as row
counts. A row count is inventory, not a finding. This script turns three of
them into measured, per-year series, and it reports how wrong each classifier
is rather than hoping nobody asks.

THE RULE THIS SCRIPT IS BUILT AROUND
------------------------------------
**A classification is evidence, so it ships with an error rate.** A theme count
with no audited accuracy is not a finding; it is a regex with a press release.
Every classifier here has a hand-coded sample, and the confusion cases are
published in full (`content_audit_*.csv`) so a reader can overrule us.

Standing rule 10 applies with force: every number in docs/CONTENT_ANALYSIS.md is
regenerated by this script. Do not hand-edit them.

WHAT IT DOES NOT DO
-------------------
- It does not attribute any document to an entity. A concurrent agent owns
  entity keys; this script only reads `tribe_id` where it already exists, and
  writes it nowhere.
- It does not use, trust, or republish `action_type_rule` or
  `keyword_terms_matched` from federal_actions.csv. Those are INTERNAL: their
  values disclose the recipe, and a recipe cannot be its own ground truth.
- It does not modify data/spine/, data/clean/cedar_*, federal_actions.csv, or
  review/cedar_*.html.

USAGE
    py -3 code/78_content_analysis.py --emit-audit   # draw hand-coding samples
    py -3 code/78_content_analysis.py               # build series + accuracy

The audit files are drawn with a FROZEN seed and the classifiers are frozen
before drawing. Errors found in the audit are REPORTED, not patched - patching
a classifier against its own audit sample turns a measurement into a claim.
"""

